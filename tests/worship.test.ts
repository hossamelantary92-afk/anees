import assert from 'node:assert/strict';
import {blankDay,loadWorship,isWorshipData,archiveAdhkar,loadAdhkarHistory,summarize,dateKey,validDate,validHistory} from '../src/utils/worship';
const memory=new Map<string,string>();
Object.assign(globalThis,{window:{localStorage:{getItem:(k:string)=>memory.get(k)??null,setItem:(k:string,v:string)=>memory.set(k,v)}}});
const d=loadWorship();
assert(isWorshipData(d));
d.days['2026-11-01']={...blankDay(),prayers:['الفجر'],quran:{'صفحة':5,'دقيقة':15},quranUnit:'دقيقة',deeds:['صدقة']};
d.bookmark='البقرة 25';
memory.set('hisn_worship',JSON.stringify(d));
assert.deepEqual(loadWorship(),d,'backup serialization preserves independent Quran units and records');
const bad=JSON.parse(JSON.stringify(d));bad.days['2026-11-01'].quran['صفحة']=-2;assert(!isWorshipData(bad));
assert(!validDate('2026-02-31'));assert(!validHistory({'2026-11-01':{morning:{completed:20,total:15},evening:{completed:0,total:15}}}));
const old={...d.plan,custom:[null]};assert(!isWorshipData({...d,plan:old}));
archiveAdhkar('2026-11-01',{'m-1':0});archiveAdhkar('2026-11-02',{'m-1':1});
assert.equal(loadAdhkarHistory()['2026-11-01'].morning.completed,1,'new day does not overwrite prior progress');
assert.equal(loadAdhkarHistory()['2026-11-02'].morning.completed,0);
assert.equal(summarize({'e-1':0}).evening.completed,1);
assert.equal(dateKey(new Date(2026,10,2,0,5)),'2026-11-02');
assert.equal(JSON.parse(memory.get('hisn_worship')!).days['2026-11-02'],undefined,'unrecorded day remains absent');
console.log('Worship data, independent Quran units, history archive and validation checks passed.');
